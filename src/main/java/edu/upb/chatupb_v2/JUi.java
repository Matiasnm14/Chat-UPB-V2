    private void jbConectarActionPerformed(java.awt.event.ActionEvent evt) {
        String ip = jIP.getText();
        String user = jTextUserName.getText();

        new Thread(() -> {
            try {
                if (server == null) {
                    server = new ChatServer();
                }
                SocketClient socketClient = new SocketClient(ip);

                int dialogResult = javax.swing.JOptionPane.showConfirmDialog(this,
                        "Incoming connection from " + server.getId() + " " + user + ". Accept?", "Connection",
                        javax.swing.JOptionPane.YES_NO_OPTION);

                if (dialogResult == javax.swing.JOptionPane.YES_OPTION) {
                    System.out.println("Client accepted.");
                    jOnline.setText("Online");
                    socketClient.start();
                } else {
                    socketClient.close();
                    System.out.println("Connection rejected.");
                }
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Connection Error: " + e.getMessage());
                e.printStackTrace();
            }
        }).start();
        if (server != null) {
            new Thread(() -> {
                while (true) {
                    try {
                        server.enviarHello();
                        Thread.sleep(100);
                    } catch (InterruptedException e) {
                        throw new RuntimeException(e);
                    }
                }
            }).start();
        }
    }//GEN-LAST:event_jbConectarActionPerformed

    private void jbEnviarActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            if (server != null) { // Verifica que haya conexión
                server.enviarMensaje(jTextMensaje.getText());
                jTextMensaje.setText(""); // Limpia el campo después de enviar
            } else {
                System.out.println("Error: No hay ningún cliente conectado para enviar el mensaje.");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jbEnviarActionPerformed

