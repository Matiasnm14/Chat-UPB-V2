    private void jbConectarActionPerformed(java.awt.event.ActionEvent evt) {
        String ip = jIP.getText();
        String user = jTextUserName.getText();
        String myUserId = String.valueOf(System.currentTimeMillis());

        new Thread(() -> {
            try {
                if (server == null) {
                    server = new ChatServer();
                }
                // 1. Crear la conexión saliente
                socketClient = new SocketClient(ip);

                // 2. Asignar EL MISMO listener que usa el servidor
                socketClient.setListener(connectionListener);

                // 3. Iniciar escucha
                socketClient.start();

                // 4. Enviar invitación
                Invitation myInvite = new Invitation(myUserId, user);
                socketClient.send(myInvite.createFormat());

                SwingUtilities.invokeLater(() -> jOnline.setText("Status: Enviando invitación..."));

            } catch (Exception e) {
                SwingUtilities.invokeLater(() ->
                        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage())
                );
            }
        }).start();
        if (server != null) {
            new Thread(() -> {
                while (true) {
                    try {
                        server.enviarHello();
                        Thread.sleep(100);
                    } catch (InterruptedException e) {
                        throw new RuntimeException(e);
                    }
                }
            }).start();
        }
    }//GEN-LAST:event_jbConectarActionPerformed

    private void jbEnviarActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            if (server != null) { // Verifica que haya conexión
                server.enviarMensaje(jTextMensaje.getText());
                jTextMensaje.setText(""); // Limpia el campo después de enviar
            } else {
                System.out.println("Error: No hay ningún cliente conectado para enviar el mensaje.");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jbEnviarActionPerformed

